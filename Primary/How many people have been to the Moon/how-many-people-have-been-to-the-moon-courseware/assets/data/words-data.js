function moonImagePath(key, kind) {
  if (!key) key = "moon";
  key = String(key).toLowerCase().replace(/ /g, "-");
  if (kind === "story") return "images/story/" + key + ".jpg";
  if (kind === "meaning") return "images/words-meaning/" + key + ".jpg";
  return "images/words/" + key + ".jpg";
}
function getMoonWordImage(w) {
  const key = (w && (w.image || w.imageKey)) || "moon";
  return moonImagePath(key, "words");
}
function getMoonMeaningImage(w) {
  const key = (w && (w.image || w.imageKey)) || "moon";
  return moonImagePath(key, "meaning");
}
